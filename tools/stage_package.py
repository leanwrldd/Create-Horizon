"""Assemble the full package the launcher builds, under target/package/:

    mod/                 the manifest, Cargo.toml, Cargo.lock (registry lock) and src/ (code, compat layer, kinetics)
  + content assets/ data  generated by tools/gen_content.py, with Create's art imported from the user's own jar

    python tools/stage_package.py [create jar]      (default: the jar in the launcher's create-resources folder)
    horizon-launcher native-build target/package --instance <instance> --version <developer tag> --trust-native-code

target/ is not committed, so neither is the art. Run `python tools/gen_modules.py`, `gen_forward.py` and
`gen_parts.py` first when the module list changed (they write into mod/).
"""
import os
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_content import stage  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_JAR = Path(os.environ.get("APPDATA", "")) / "horizon" / "horizon-mods" / "create-resources" / "create-1.21.1-6.0.10.jar"


def main():
    jar = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_JAR
    if not jar.is_file():
        raise SystemExit(f"Create's jar was not found: {jar}")
    dest = ROOT / "target" / "package"
    if dest.exists():
        shutil.rmtree(dest)
    # The package takes `src/` code, the manifests and the resource trees, and nothing else: copy only those.
    shutil.copytree(ROOT / "mod", dest, ignore=shutil.ignore_patterns("target", ".horizon", "__pycache__"))
    stage(jar, dest)
    print(f"Staged {dest}")


if __name__ == "__main__":
    main()
