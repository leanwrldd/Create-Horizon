"""Write mod/src/forward.rs: `Create`, the mod's `Hooks`, handing each hook listed in
tools/forward_hooks.txt to every module in turn.

    python tools/gen_forward.py [generated api dir, default target/apigen]

The signatures come from Horizon's generated `trait Hooks` (the minecraft-horizon-modding skill's
apigen writes `mod_api_generated.rs`; run rustfmt on it first). A hook that returns `Flow` stops at
the first module that cancels, one that returns an `Option` at the first answer, and any other
reaches every module, as Horizon's own dispatch treats separate mods.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
api = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "target" / "apigen"
if not (api / "mod_api_generated.rs").exists():
    # a worktree has no target/: the main checkout's is the old API's frozen copy
    api = ROOT.parent.parent.parent / "target" / "apigen"
source = (api / "mod_api_generated.rs").read_text(encoding="utf-8")
trait = source[source.index("pub trait Hooks"):]
names = [line.strip() for line in (ROOT / "tools" / "forward_hooks.txt").read_text().splitlines()
         if line.strip() and not line.startswith("#")]

out = ['//! Generated by tools/gen_forward.py from tools/forward_hooks.txt: do not edit by hand.',
       '//!',
       '//! The mod combines `Core`, the machine modules, and Ponder.',
       '//! Each hook here goes to every one of them in order.',
       '',
       '#![allow(clippy::needless_lifetimes)]',
       '',
       'use crate::compat::*;',
       '',
       'pub struct Create {',
       '    pub modules: Vec<Box<dyn Hooks>>,',
       '}',
       '',
       'impl Hooks for Create {']
for name in names:
    match = re.search(r"\n    fn %s\(\s*&self,?(.*?)\)( -> (.*?))? \{\n" % re.escape(name), trait, re.S)
    if not match:
        sys.exit(f"no hook named {name} in {api}")
    params = " ".join(match.group(1).split()).rstrip(",")
    returns = match.group(3)
    # Split on commas outside angle brackets.
    depth, parts, current = 0, [], ""
    for ch in params:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current.strip())
    args = ", ".join(part.split(":")[0].strip() for part in parts)
    signature = f"    fn {name}(&self, {', '.join(parts)})" + (f" -> {returns}" if returns else "")
    fallback = "()" if returns is None else "Flow::Continue" if returns == "Flow" else "None"
    call = f"guarded(\"{name}\", index, {fallback}, || module.{name}({args}))"
    if returns is None:
        body = [f"        for (index, module) in self.modules.iter().enumerate() {{", f"            {call};", "        }"]
    elif returns == "Flow":
        body = [f"        for (index, module) in self.modules.iter().enumerate() {{",
                f"            if let Flow::Cancel = {call} {{",
                "                return Flow::Cancel;", "            }", "        }",
                "        Flow::Continue"]
    elif name == "block_entity_update_tag":
        # The value boxes' saved values (filters, scroll values) go to the client with every block's tag: a
        # module needn't send them (`machines/value_box.rs`, `decorate`).
        body = [f"        for (index, module) in self.modules.iter().enumerate() {{",
                f"            if let Some(mut answer) = {call} {{",
                "                crate::machines::value_box::decorate(&event.entity.id, &event.entity.nbt, &mut answer);",
                "                return Some(answer);", "            }", "        }",
                "        None"]
    elif returns.startswith("Option<"):
        body = [f"        for (index, module) in self.modules.iter().enumerate() {{",
                f"            if let Some(answer) = {call} {{",
                "                return Some(answer);", "            }", "        }",
                "        None"]
    else:
        sys.exit(f"{name} returns {returns}: write its forwarding by hand")
    out += [signature + " {", *body, "    }", ""]
out[-1] = "}"
(ROOT / "mod" / "src" / "forward.rs").write_text("\n".join(out) + "\n", encoding="utf-8",
                                                           newline="\n")
print(f"{len(names)} hooks forwarded")
