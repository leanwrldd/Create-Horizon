"""Write MIGRATION.md's generated tables: the hooks that are not wired yet (with the modules that answer them) and the
old Host methods the compatibility layer still answers with a logged neutral value.

    python tools/gen_migration.py

The hook classes come from tools/hook_map.txt; the modules from `fn <hook>(` in mod/src; the Host methods from
mod/src/compat/old_api.rs (all) minus what mod/src/compat/adapter.rs overrides.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = []
for line in (ROOT / "tools" / "hook_map.txt").read_text(encoding="utf-8").splitlines():
    if line.startswith("#") or not line.strip():
        continue
    parts = line.split(None, 1)
    name, rest = parts[0], parts[1]
    kind = re.match(r"(global \(wired\)|part \(wired\)|global \(not wired\)|part \(not wired\)|no direct match)", rest).group(1)
    rows.append((name, kind, rest[len(kind):].strip()))

sources = {}
for path in (ROOT / "mod" / "src").rglob("*.rs"):
    if "kinetics" in path.parts or "compat" in path.parts or path.name in ("forward.rs", "parts.rs"):
        continue
    sources[path.relative_to(ROOT / "mod" / "src").as_posix()] = path.read_text(encoding="utf-8")


def modules_of(hook):
    found = [name for name, text in sources.items() if re.search(r"\bfn %s\(" % re.escape(hook), text)]
    return sorted(Path(n).stem for n in found)


old_api = (ROOT / "mod" / "src" / "compat" / "old_api.rs").read_text(encoding="utf-8")
host_body = old_api[old_api.index("pub trait Host {"):]
all_methods = sorted(set(re.findall(r"\n    fn (\w+)\(", host_body)) - {"new_host", "new_server"})
adapter = (ROOT / "mod" / "src" / "compat" / "adapter.rs").read_text(encoding="utf-8")
impl = adapter[adapter.index("impl Host for Adapter"):adapter.index("impl From<DisplayContext>")]
done = set(re.findall(r"\n    fn (\w+)\(", impl)) - {"new_host", "new_server"}
gaps = [m for m in all_methods if m not in done]

out = ["<!-- Generated by tools/gen_migration.py: the tables below. The prose above them is written by hand. -->", ""]
out += ["### Hooks not wired yet", "",
        "| Old hook | Class | New mechanism | Modules that answer it |", "|---|---|---|---|"]
for name, kind, new in rows:
    if "(wired)" in kind:
        continue
    mods = modules_of(name)
    out.append(f"| `{name}` | {kind} | {new} | {', '.join(mods) if mods else '(none)'} |")
out += ["", f"### Old `Host` methods still answered with a neutral value ({len(gaps)} of {len(all_methods)})", "",
        "Each logs `create: compat gap: Host::<name> ...` once. Implemented: " + ", ".join(f"`{m}`" for m in sorted(done)) + ".", ""]
out.append(", ".join(f"`{m}`" for m in gaps))
out.append("")

target = ROOT / "MIGRATION.md"
text = target.read_text(encoding="utf-8") if target.exists() else ""
marker = "<!-- Generated by tools/gen_migration.py"
if marker in text:
    text = text[:text.index(marker)]
target.write_text(text.rstrip("\n") + "\n\n" + "\n".join(out), encoding="utf-8", newline="\n")
print(f"{len(rows)} hooks, {len(gaps)} host gaps")
