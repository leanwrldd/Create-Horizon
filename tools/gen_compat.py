"""Write the compatibility layer's generated half, mod/src/compat/old_api.rs: the OLD mod API's names, as the
137 machine modules were written against them.

    python tools/gen_compat.py [old generated api dir, default target/apigen]

Inputs:
  * `mod_api_generated.rs`        the old `trait Hooks` and its event structs (Horizon 9f42064, see the
                                  minecraft-horizon-modding skill's apigen);
  * `mod_api_generated_host.rs`   the old `trait Host`;
  * tools/forward_hooks.txt       the 75 hooks the modules answer;
  * mod/src/**.rs                 which `Host` methods the modules call.

Output: `trait Hooks` with those 75 methods, their event structs verbatim, and `trait Host` with the methods the
modules call, every default a logged neutral value (`gap`) that `compat/adapter.rs` overrides where the new API has an
equivalent. The old API is frozen, so this is a one-time conversion: the output is committed, and this script is
only needed again to add a hook or a method.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
api = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent.parent.parent / "target" / "apigen"
if not (api / "mod_api_generated.rs").exists():
    api = ROOT / "target" / "apigen"
hooks_src = (api / "mod_api_generated.rs").read_text(encoding="utf-8")
host_src = (api / "mod_api_generated_host.rs").read_text(encoding="utf-8")
names = [line.strip() for line in (ROOT / "tools" / "forward_hooks.txt").read_text().splitlines()
         if line.strip() and not line.startswith("#")]


def trait_body(source, header):
    start = source.index(header)
    end = source.index("\n}\n", start)
    return source[start:end]


def methods(body):
    """{name: (signature text up to ` {`, full text)} for each 4-space-indented method."""
    found = {}
    lines = body.split("\n")
    i = 0
    while i < len(lines):
        m = re.match(r"    fn (\w+)\(", lines[i])
        if not m:
            i += 1
            continue
        j = i
        while not lines[j].startswith("    }"):
            j += 1
        found[m.group(1)] = "\n".join(lines[i:j + 1])
        i = j + 1
    return found


hooks_methods = methods(trait_body(hooks_src, "pub trait Hooks"))
host_methods = methods(trait_body(host_src, "pub trait Host"))

# --- the hooks and their events -------------------------------------------------------------------------
events = []
trait_lines = ["/// The old `Hooks`: the 75 moments the modules answer, each with the OLD event and the OLD `Host`.",
               "/// `forward.rs` (generated by tools/gen_forward.py) hands each one to every module in turn.",
               "pub trait Hooks: Send + Sync {"]
for name in names:
    text = hooks_methods.get(name)
    if text is None:
        sys.exit(f"no hook named {name} in {api}")
    trait_lines.append(text)
    ev = re.search(r"event: &mut (\w+)", text)
    if ev:
        events.append(ev.group(1))
trait_lines.append("}")


def struct_text(source, name):
    m = re.search(r"((?:#\[[^\n]*\]\n)*)pub struct %s\b[^\n]*\{.*?\n\}\n" % re.escape(name), source, re.S)
    if not m:
        sys.exit(f"no struct {name}")
    return m.group(0)


out = ["// Generated by tools/gen_compat.py from the old mod API (Horizon 9f42064): do not edit by hand.",
       "#![allow(unused_variables, clippy::all)]", "use super::*;", ""]
out += trait_lines + [""]
seen = set()
for ev in events:
    if ev in seen:
        continue
    seen.add(ev)
    text = struct_text(hooks_src, ev)
    out.append(re.sub(r"(?m)^#\[non_exhaustive\]\n", "", text))

# --- the host methods the modules call ------------------------------------------------------------------
src = ""
for path in (ROOT / "mod" / "src").rglob("*.rs"):
    if "kinetics" in path.parts or "compat" in path.parts:
        continue
    src += path.read_text(encoding="utf-8") + "\n"
called = set(re.findall(r"\.(\w+)\(", src))
used = sorted(n for n in host_methods if n in called)


def neutral(returns):
    r = returns.strip()
    if r == "" or r == "()":
        return ""
    if r == "bool":
        return "false"
    if r.startswith("Option<") or r.startswith("&mut ") and False:
        return "None"
    if r.startswith("Vec<"):
        return "Vec::new()"
    if r.startswith("&["):
        return "&[]"
    if r.startswith("&'static str") or r == "&str":
        return '""'
    if r in ("u32", "u64", "i32", "i64", "usize", "f32", "f64", "u8", "i8", "u16"):
        return "0"
    if r.startswith("Result<"):
        return 'Err(Default::default())' if "String" not in r else 'Err("unavailable in the compatibility layer".into())'
    if r.startswith("(") and r.endswith(")"):
        return "Default::default()"
    return "Default::default()"


host_lines = ["", "/// The old `Host`: only the methods the modules call. Every default is a logged neutral value;",
              "/// `adapter.rs` overrides the ones the new API can answer.",
              "pub trait Host {"]
for name in used:
    text = host_methods[name]
    head, _, _ = text.partition("{\n")
    sig = head.rstrip()
    ret = re.search(r"\)\s*->\s*(.+)$", " ".join(sig.split()))
    value = neutral(ret.group(1) if ret else "")
    body = f'        gap("{name}");' + (f"\n        {value}" if value else "")
    host_lines.append(f"{sig} {{\n{body}\n    }}")
host_lines.append("}")
out += host_lines
(ROOT / "mod" / "src" / "compat").mkdir(parents=True, exist_ok=True)
(ROOT / "mod" / "src" / "compat" / "old_api.rs").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
# The names, explicitly, so they win over the glob of the new API that compat/mod.rs re-exports.
listing = ["Hooks", "Host"] + sorted(seen)
(ROOT / "mod" / "src" / "compat" / "old_names.rs").write_text(
    "// Generated by tools/gen_compat.py: do not edit by hand. `include!`d by compat/mod.rs.\n"
    "pub use self::old_api::{\n    " + ",\n    ".join(listing) + ",\n};\n",
    encoding="utf-8", newline="\n")
print(f"{len(names)} hooks, {len(seen)} events, {len(used)} host methods")
missing = sorted(n for n in set(re.findall(r"\bhost\.(\w+)\(", src)) if n not in host_methods)
print("called on `host.` but not in the old Host:", missing)
