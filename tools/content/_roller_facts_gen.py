"""One-off generator for the block facts the Mechanical Roller's filter asks (not a plugin: the leading
underscore keeps tools/gen_content.py from loading it). Writes mod/src/kinetics/src/rules/roller_facts.rs.

    python tools/content/_roller_facts_gen.py [prepared game data dir]

`RollerBlockEntity.isValidMaterial` takes a block item whose state to pave with (`getStateToPaveWith`: the
block's default state, a slab made `DOUBLE`) is not air, not an `EntityBlock`, not a `StairBlock`, has an
outline shape that is the full cube and a collision shape that isn't empty. Horizon's `Host` can't ask a
block that before it is placed, so vanilla's answer is baked in from the prepared game data
(`gameplay-facts.json` has each state's outline, `block_entity` and whether its collision is the full cube;
`block-behaviours.json` its class chain). Rerun it when the game version changes.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "mod/src/kinetics/src/rules/roller_facts.rs"

FULL = [[0.0, 0.0, 0.0, 1.0, 1.0, 1.0]]
# Blocks whose outline is the full cube and whose collision shape is smaller than it but not empty
# (`MudBlock`'s 14 pixels, `SoulSandBlock`'s 14, `HoneyBlock`'s 15). The rest of the full-outline blocks with no
# full collision (cobweb, vines, tall grass, powder snow...) have an empty collision shape.
SHORT_COLLISION = {"minecraft:honey_block", "minecraft:mud", "minecraft:soul_sand"}


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    facts = json.loads((data / "facts.json").read_text(encoding="utf-8"))["defaults"]
    states = json.loads((data / "gameplay-facts.json").read_text(encoding="utf-8"))["states"]
    classes = {b["name"]: b["class"] for b in
               json.loads((data / "block-behaviours.json").read_text(encoding="utf-8"))["blocks"]}
    valid = []
    for name, index in sorted(facts.items()):
        if not name.startswith("minecraft:") or name == "minecraft:air":
            continue
        state = states[index]
        chain = classes.get(name, [])
        if state["block_entity"] or "StairBlock" in chain:
            continue
        slab = "SlabBlock" in chain
        if not slab and state["outline"] != FULL:
            continue
        if not slab and not state["full_collision"] and name not in SHORT_COLLISION:
            continue
        valid.append(name)
    lines = [
        "//! Generated by tools/content/_roller_facts_gen.py: do not edit by hand.",
        "//!",
        "//! What `RollerBlockEntity.isValidMaterial` asks of a vanilla block that Horizon's `Host` cannot answer before",
        "//! it is placed: the blocks whose paving state is a full cube with a collision shape, no block entity and no",
        "//! stairs, from the prepared game data. Sorted, for a binary search.",
        "",
        "pub const PAVE_MATERIALS: &[&str] = &[",
        *(f'    "{name}",' for name in valid),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(valid)} blocks")


if __name__ == "__main__":
    main()
