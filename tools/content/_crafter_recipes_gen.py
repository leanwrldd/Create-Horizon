"""One-off generator for the Mechanical Crafter's vanilla crafting table (not a plugin: the leading
underscore keeps tools/gen_content.py from loading it). Writes _crafter_recipes.py beside it;
crafter.py imports that, so the build never needs the game data.

    python tools/content/_crafter_recipes_gen.py [prepared game data dir]

Create's crafter also crafts what a crafting table does (`RecipeGridHandler.tryToApplyRecipe`:
`getRecipeFor(RecipeType.CRAFTING, ...)`, `allowRegularCraftingInCrafter`, on by default), but
Horizon's `Host` cannot list the game's crafting recipes (`recipes_of_type` reads only a type
outside `minecraft`). So the shaped and shapeless crafting recipes of the prepared game data
(`data/minecraft/recipe`) are baked in here as recipes of two types of Create's own, which the
glue reads with `Host::recipes_of_type`:

    create:crafter_baked_shaped      {"pattern": [...], "key": {...}, "result": {...}}
    create:crafter_baked_shapeless   {"ingredients": [...], "result": {...}}

What is left out: the transmuting recipes (shulker boxes keep their contents and components, which
a baked table cannot copy), the dyeing and special recipes (`crafting_dye`, banners, books, maps,
fireworks, repairs, decorated pots): the crafter runs `RecipeGridHandler.isRecipeAllowed` against
fireworks anyway. A data pack's changes to the crafting recipes are not seen.
"""

import json
import sys
from pathlib import Path

DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
TYPES = {"minecraft:crafting_shaped": "create:crafter_baked_shaped",
         "minecraft:crafting_shapeless": "create:crafter_baked_shapeless"}


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    folder = data / "data" / "minecraft" / "recipe"
    baked = {}
    for path in sorted(folder.glob("*.json")):
        recipe = json.loads(path.read_text(encoding="utf-8"))
        kind = TYPES.get(recipe.get("type"))
        if kind is None:
            continue
        fields = ("pattern", "key") if "pattern" in recipe else ("ingredients",)
        baked[f"crafter_baked/{path.stem}"] = {
            "type": kind,
            **{f: recipe[f] for f in fields},
            "result": {k: v for k, v in recipe["result"].items() if k in ("id", "count", "components")},
        }
    lines = [f"    {key!r}: {value!r}," for key, value in baked.items()]
    text = ('"""The vanilla shaped and shapeless crafting recipes of the prepared game data, as '
            'recipes of Create\'s own types (generated by _crafter_recipes_gen.py)."""\n\n'
            "BAKED = {\n" + "\n".join(lines) + "\n}\n")
    (Path(__file__).resolve().parent / "_crafter_recipes.py").write_text(text, encoding="utf-8", newline="\n")
    print(len(baked), "recipes")


if __name__ == "__main__":
    main()
