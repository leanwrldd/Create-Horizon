"""One-off generator for the hardness table the Mechanical Drill and Saw read (not a plugin: the
leading underscore keeps tools/gen_content.py from loading it). Writes
native/kinetics/src/rules/drill_hardness.rs.

    python tools/content/_drill_hardness_gen.py [prepared game data dir]

Horizon's `Host` has no way to ask a block for its hardness (`BlockState.getDestroySpeed`), which
Create's `BlockBreakingKineticBlockEntity` needs, so the numbers are baked in: vanilla's from the
prepared game data (`facts.json` names each state's block, `gameplay-facts.json` holds its
`hardness` and `liquid`, same order), and this mod's own blocks from the declarations under
content/ (their `properties.hardness`). Rerun it when the game version or the declared blocks
change.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "native/kinetics/src/rules/drill_hardness.rs"


def number(value):
    text = repr(float(value))
    return text if "." in text or "e" in text else text + ".0"


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    facts = json.loads((data / "facts.json").read_text(encoding="utf-8"))["states"]
    gameplay = json.loads((data / "gameplay-facts.json").read_text(encoding="utf-8"))["states"]
    assert len(facts) == len(gameplay)
    hardness, liquids = {}, set()
    for state, extra in zip(facts, gameplay):
        name = state[0]
        if not name.startswith("minecraft:"):
            continue
        # Every state of a block has the block's hardness (checked when this was written).
        hardness.setdefault(name, extra["hardness"])
        if extra["liquid"]:
            liquids.add(name)
    for path in sorted((ROOT / "content/data/create/horizon/block").glob("*.json")):
        declared = json.loads(path.read_text(encoding="utf-8"))
        value = declared.get("properties", {}).get("hardness")
        if value is not None:
            hardness[f"create:{path.stem}"] = value
    rows = "".join(f'    ("{name}", {number(value)}),\n' for name, value in sorted(hardness.items()))
    liquid_rows = "".join(f'    "{name}",\n' for name in sorted(liquids))
    OUT.write_text(f'''//! Generated by tools/content/_drill_hardness_gen.py: do not edit by hand.
//!
//! `BlockState.getDestroySpeed` (the block's hardness) by block id, for the blocks Horizon's
//! prepared game data and this mod's declarations name. Horizon's `Host` cannot ask a block.

/// `(block id, hardness)`, sorted by id; -1 is unbreakable.
pub const HARDNESS: &[(&str, f32)] = &[
{rows}];

/// The blocks `BlockState.liquid()` holds for.
pub const LIQUIDS: &[&str] = &[
{liquid_rows}];
''', encoding="utf-8", newline="\n")
    print(f"{len(hardness)} blocks, {len(liquids)} liquids")


if __name__ == "__main__":
    main()
