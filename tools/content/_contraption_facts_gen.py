"""One-off generator for the block facts the contraption rules read (not a plugin: the leading
underscore keeps tools/gen_content.py from loading it). Writes
native/kinetics/src/rules/contraption_facts.rs.

    python tools/content/_contraption_facts_gen.py [prepared game data dir]

Create's `BlockMovementChecks` asks a block state for `getPistonPushReaction()` and
`canBeReplaced()`, which Horizon's `Host` cannot answer, so vanilla's are baked in from the
prepared game data (`facts.json` names each state's block, `gameplay-facts.json` holds its `push`
and `replaceable`, same order). This mod's own blocks all push normally and none is replaceable.
Rerun it when the game version changes.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "native/kinetics/src/rules/contraption_facts.rs"


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    facts = json.loads((data / "facts.json").read_text(encoding="utf-8"))["states"]
    gameplay = json.loads((data / "gameplay-facts.json").read_text(encoding="utf-8"))["states"]
    assert len(facts) == len(gameplay)
    blocking, push_only, replaceable = set(), set(), set()
    for state, extra in zip(facts, gameplay):
        name = state[0]
        if not name.startswith("minecraft:"):
            continue
        # `PushReaction.BLOCK` is the game data's IMMOVEABLE, `PUSH_ONLY` its PUSH.
        if extra["push"] == "IMMOVEABLE":
            blocking.add(name)
        elif extra["push"] == "PUSH":
            push_only.add(name)
        if extra["replaceable"]:
            replaceable.add(name)

    def rows(names):
        return "".join(f'    "{name}",\n' for name in sorted(names))

    OUT.write_text(f'''//! Generated by tools/content/_contraption_facts_gen.py: do not edit by hand.
//!
//! What `BlockMovementChecks` asks a vanilla block state that Horizon's `Host` cannot answer:
//! `getPistonPushReaction()` and `canBeReplaced()`, by block id, from the prepared game data.

/// `PushReaction.BLOCK`: a piston and a contraption cannot move these.
pub const BLOCKS_PUSH: &[&str] = &[
{rows(blocking)}];

/// `PushReaction.PUSH_ONLY`: moved, but never pulled back by a sticky piston.
pub const PUSH_ONLY: &[&str] = &[
{rows(push_only)}];

/// `BlockState.canBeReplaced()`.
pub const REPLACEABLE: &[&str] = &[
{rows(replaceable)}];
''', encoding="utf-8", newline="\n")
    print(f"{len(blocking)} blocking, {len(push_only)} push-only, {len(replaceable)} replaceable")


main()
