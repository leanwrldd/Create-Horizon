"""One-off generator for what a Deployer needs to know of the item in its hand and of the blocks it
mines (not a plugin: the leading underscore keeps tools/gen_content.py from loading it). Writes
native/kinetics/src/rules/deployer_items.rs.

    python tools/content/_deployer_items_gen.py [prepared game data dir]

Horizon's `Host` cannot ask an item for its attack damage, its mining speed, its durability or
whether it is the right tool for a block (`ItemStack.getDestroySpeed`, `isCorrectForDrops`,
`Item.hurtEnemy`), and cannot ask a block whether it needs the right tool for its drops
(`BlockBehaviour.requiresCorrectToolForDrops`). The game's prepared data has both, so the numbers
are baked in: items from `items.json` (the item components the game was prepared with:
`minecraft:attribute_modifiers`, `minecraft:tool`, `minecraft:weapon`, `minecraft:max_damage`),
blocks from `facts.json` and `gameplay-facts.json` (`requires_tool`), and this mod's own blocks
from the declarations (`properties.requires_tool`). Rerun it when the game version or the
declared blocks change.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
TOOLS = ROOT / "tools"
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "native/kinetics/src/rules/deployer_items.rs"


def number(value):
    text = repr(float(value))
    return text if "." in text or "e" in text or "inf" in text else text + ".0"


def rust_str(text):
    return json.dumps(text)


def items(data):
    table = json.loads((data / "items.json").read_text(encoding="utf-8"))
    rows = []
    for name, comps in sorted(table.items()):
        attack = sum(m["amount"] for m in comps.get("minecraft:attribute_modifiers", [])
                     if m["type"] == "minecraft:attack_damage" and m["operation"] == "add_value"
                     and m["slot"] in ("mainhand", "any"))
        max_damage = comps.get("minecraft:max_damage", 0)
        tool = comps.get("minecraft:tool")
        weapon = comps.get("minecraft:weapon")
        if not (attack or max_damage or tool or weapon):
            continue
        rules = []
        if tool:
            for rule in tool["rules"]:
                blocks = rule["blocks"]
                assert isinstance(blocks, str), (name, blocks)
                rules.append((blocks, rule.get("speed"), rule.get("correct_for_drops")))
        rows.append({
            "id": name, "attack": attack, "max_damage": max_damage,
            "tool": tool is not None,
            "default_speed": (tool or {}).get("default_mining_speed", 1.0),
            "damage_per_block": (tool or {}).get("damage_per_block", 1),
            "weapon": weapon is not None,
            "damage_per_attack": (weapon or {}).get("item_damage_per_attack", 1),
            "rules": rules,
        })
    return rows


def requires_tool(data):
    facts = json.loads((data / "facts.json").read_text(encoding="utf-8"))["states"]
    gameplay = json.loads((data / "gameplay-facts.json").read_text(encoding="utf-8"))["states"]
    assert len(facts) == len(gameplay)
    names = set()
    for state, extra in zip(facts, gameplay):
        if state[0].startswith("minecraft:") and extra["requires_tool"]:
            names.add(state[0])
    sys.path.insert(0, str(TOOLS))
    import gen_content
    for name, declared in gen_content.collect().blocks.items():
        if declared.get("properties", {}).get("requires_tool"):
            names.add(f"create:{name}")
    return sorted(names)


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    rows = items(data)
    blocks = requires_tool(data)
    lines = []
    for row in rows:
        rules = "".join(
            f"        Rule {{ blocks: {rust_str(b)}, speed: {number(s) if s is not None else 'NO_SPEED'}, "
            f"correct: {'Some(true)' if c is True else 'Some(false)' if c is False else 'None'} }},\n"
            for b, s, c in row["rules"])
        rules_text = f"&[\n{rules}    ]" if rules else "&[]"
        lines.append(
            f"    Item {{\n        id: {rust_str(row['id'])}, attack: {number(row['attack'])}, "
            f"max_damage: {row['max_damage']},\n        tool: {str(row['tool']).lower()}, "
            f"default_speed: {number(row['default_speed'])}, damage_per_block: {row['damage_per_block']},\n"
            f"        weapon: {str(row['weapon']).lower()}, damage_per_attack: {row['damage_per_attack']},\n"
            f"        rules: {rules_text},\n    }},\n")
    block_rows = "".join(f"    {rust_str(b)},\n" for b in blocks)
    OUT.write_text(f'''//! Generated by tools/content/_deployer_items_gen.py: do not edit by hand.
//!
//! What the game's own data says of the items a Deployer can hold (their attack damage, durability
//! and tool rules: `minecraft:attribute_modifiers`, `max_damage`, `tool`, `weapon`) and of the
//! blocks that need the right tool for their drops. Horizon's `Host` cannot ask either.

/// A tool rule's speed when it names none (`Tool.Rule.speed` empty).
pub const NO_SPEED: f32 = -1.0;

/// `Tool.Rule`: the blocks it is for (`#tag` or a block id), the mining speed it gives and
/// whether the item is the right tool for those blocks' drops (`correct_for_drops`).
#[derive(Clone, Copy, Debug)]
pub struct Rule {{
    pub blocks: &'static str,
    pub speed: f32,
    pub correct: Option<bool>,
}}

/// One item's components that matter to a Deployer.
#[derive(Clone, Copy, Debug)]
pub struct Item {{
    pub id: &'static str,
    /// The sum of its mainhand `attack_damage` modifiers (added to the player's own 1).
    pub attack: f32,
    /// `minecraft:max_damage`; 0 for an item that doesn't wear.
    pub max_damage: u32,
    pub tool: bool,
    /// `Tool.defaultMiningSpeed`.
    pub default_speed: f32,
    /// `Tool.damagePerBlock`.
    pub damage_per_block: u32,
    /// Has `minecraft:weapon`, and what each attack costs it (`item_damage_per_attack`).
    pub weapon: bool,
    pub damage_per_attack: u32,
    pub rules: &'static [Rule],
}}

/// Sorted by id.
pub const ITEMS: &[Item] = &[
{"".join(lines)}];

/// The vanilla and Create blocks that need the right tool to drop anything
/// (`requiresCorrectToolForDrops`), sorted.
pub const REQUIRES_TOOL: &[&str] = &[
{block_rows}];
''', encoding="utf-8", newline="\n")
    print(f"{len(rows)} items, {len(blocks)} blocks needing a tool")


if __name__ == "__main__":
    main()
