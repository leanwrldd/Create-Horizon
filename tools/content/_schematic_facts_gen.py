"""One-off generator for the block facts the Schematicannon's rules read (not a plugin: the leading
underscore keeps tools/gen_content.py from loading it). Writes
native/kinetics/src/rules/schematic_facts.rs.

    python tools/content/_schematic_facts_gen.py [prepared game data dir]

Create's `ItemRequirement.defaultOf` asks a block for `asItem()`, `SchematicPrinter.shouldPlaceBlock`
for `BlockState.getDestroySpeed(...) == -1`, `hasBlockEntity()` and `isRedstoneConductor()`, none of
which Horizon's `Host` answers, so vanilla's are baked in from the prepared game data (`facts.json`
names each state's block, `gameplay-facts.json` holds its `item`, `hardness`, `block_entity` and
`solid_render`, same order). `isRedstoneConductor` is read as `solid_render`: a block that draws as a
full opaque cube (glass, leaves and the like are not). Rerun it when the game version changes.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "native/kinetics/src/rules/schematic_facts.rs"


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    facts = json.loads((data / "facts.json").read_text(encoding="utf-8"))["states"]
    gameplay = json.loads((data / "gameplay-facts.json").read_text(encoding="utf-8"))["states"]
    assert len(facts) == len(gameplay)
    item_of, unbreakable, block_entity, solid = {}, set(), set(), set()
    for state, extra in zip(facts, gameplay):
        name = state[0]
        if not name.startswith("minecraft:"):
            continue
        item = extra.get("item") or "minecraft:air"
        if item != name:
            item_of[name] = "" if item == "minecraft:air" else item
        if extra["hardness"] < 0:
            unbreakable.add(name)
        if extra["block_entity"]:
            block_entity.add(name)
        if extra["solid_render"]:
            solid.add(name)

    def rows(names):
        return "".join(f'    "{name}",\n' for name in sorted(names))

    pairs = "".join(f'    ("{name}", "{item}"),\n' for name, item in sorted(item_of.items()))
    OUT.write_text(f'''//! Generated by tools/content/_schematic_facts_gen.py: do not edit by hand.
//!
//! What the Schematicannon asks a vanilla block that Horizon's `Host` cannot answer, by block id,
//! from the prepared game data.

/// `Block.asItem()` of the blocks whose item is not their own id; an empty item is `Items.AIR`
/// (water, fire, a potted plant: the block has no item, so a cannon can't print it).
pub const ITEM_OF: &[(&str, &str)] = &[
{pairs}];

/// `getDestroySpeed == -1`: bedrock, barriers, command blocks, portals.
pub const UNBREAKABLE: &[&str] = &[
{rows(unbreakable)}];

/// `BlockState.hasBlockEntity()`.
pub const BLOCK_ENTITY: &[&str] = &[
{rows(block_entity)}];

/// Blocks drawn as a full opaque cube (`isSolidRender`), the stand-in for `isRedstoneConductor`.
pub const SOLID: &[&str] = &[
{rows(solid)}];
''', encoding="utf-8", newline="\n")
    print(f"{len(item_of)} items, {len(unbreakable)} unbreakable, {len(block_entity)} with entities, {len(solid)} solid")


main()
