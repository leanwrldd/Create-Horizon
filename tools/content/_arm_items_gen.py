"""One-off generator for what a Mechanical Arm needs to know of vanilla items (not a plugin: the
leading underscore keeps tools/gen_content.py from loading it). Writes
native/kinetics/src/rules/arm_items.rs.

    python tools/content/_arm_items_gen.py [prepared game data dir]

Horizon's `Host` can't read vanilla's campfire cooking recipes (`CampfireBlockEntity.getCookableRecipe`:
`recipes_of_type` answers only types outside `minecraft`), the composter's `ComposterBlock.COMPOSTABLES`
or an item's `JUKEBOX_PLAYABLE` component, and nothing can ask them without trying. The game's prepared
data has all three (`data/minecraft/recipe/*campfire_cooking*`, and the `minecraft:compostable` and
`minecraft:jukebox_playable` components in `items.json`), so they are baked in. Rerun it when the game
version changes.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "native/kinetics/src/rules/arm_items.rs"


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    cooking = {}
    for path in sorted((data / "data/minecraft/recipe").glob("*.json")):
        recipe = json.loads(path.read_text(encoding="utf-8"))
        if recipe.get("type") != "minecraft:campfire_cooking":
            continue
        ingredient = recipe["ingredient"]
        assert isinstance(ingredient, str) and not ingredient.startswith("#"), (path, ingredient)
        cooking[ingredient] = recipe["cookingtime"]
    items = json.loads((data / "items.json").read_text(encoding="utf-8"))
    compostable = sorted(n for n, c in items.items() if "minecraft:compostable" in c)
    playable = sorted(n for n, c in items.items() if "minecraft:jukebox_playable" in c)

    lines = [
        "//! Generated by tools/content/_arm_items_gen.py from the game's prepared data: do not edit by hand.",
        "//!",
        "//! What a Mechanical Arm can't ask the game: the campfire's cooking recipes",
        "//! (`CampfireBlockEntity.getCookableRecipe`), `ComposterBlock.COMPOSTABLES` and the items with",
        "//! `DataComponents.JUKEBOX_PLAYABLE`.",
        "",
        "/// `minecraft:campfire_cooking` recipes: the ingredient and its `cookingtime`.",
        "pub const CAMPFIRE_COOKING: &[(&str, u32)] = &[",
        *(f'    ("{item}", {time}),' for item, time in sorted(cooking.items())),
        "];",
        "",
        "/// Items with a `minecraft:compostable` component.",
        "pub const COMPOSTABLE: &[&str] = &[",
        *(f'    "{item}",' for item in compostable),
        "];",
        "",
        "/// Items with a `minecraft:jukebox_playable` component.",
        "pub const JUKEBOX_PLAYABLE: &[&str] = &[",
        *(f'    "{item}",' for item in playable),
        "];",
        "",
        "/// The `cookingtime` of the campfire recipe for `item`.",
        "pub fn cooking_time(item: &str) -> Option<u32> {",
        "    CAMPFIRE_COOKING.iter().find(|(name, _)| *name == item).map(|(_, time)| *time)",
        "}",
        "",
        "pub fn compostable(item: &str) -> bool {",
        "    COMPOSTABLE.contains(&item)",
        "}",
        "",
        "pub fn jukebox_playable(item: &str) -> bool {",
        "    JUKEBOX_PLAYABLE.contains(&item)",
        "}",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    #[test]",
        "    fn the_baked_tables_know_the_obvious() {",
        '        assert_eq!(cooking_time("minecraft:potato"), Some(600));',
        '        assert_eq!(cooking_time("minecraft:stone"), None);',
        '        assert!(compostable("minecraft:wheat") && !compostable("minecraft:diamond"));',
        '        assert!(jukebox_playable("minecraft:music_disc_13") && !jukebox_playable("minecraft:stick"));',
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(cooking)} cooking recipes, {len(compostable)} compostable, {len(playable)} records")


if __name__ == "__main__":
    main()
