"""Writes tools/content/fan_recipes.py from Create's datagen output (run by hand, never by the build).

    python tools/content/fan_recipes_gen.py [path to create-java-src]

Every `create:splashing` and `create:haunting` recipe in `src/generated/resources/data/create/recipe/`
is copied as Create's datagen wrote it, except those for other mods' items (they carry
`neoforge:conditions`). The plugin `fan.py` imports the table, so the build never reads the checkout.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else HERE.parent.parent.parent / "create-java-src")
    root = src / "src" / "generated" / "resources" / "data" / "create" / "recipe"
    table = {}
    for kind in ("splashing", "haunting"):
        for path in sorted((root / kind).rglob("*.json")):
            recipe = json.loads(path.read_text(encoding="utf-8"))
            if "neoforge:conditions" in recipe:
                continue
            table[f"{kind}/{path.relative_to(root / kind).with_suffix('').as_posix()}"] = recipe
    lines = ['"""Create\'s splashing and haunting recipes, as its datagen writes them (generated by',
             'tools/content/fan_recipes_gen.py from Create mc1.21.1/dev at 4148fd8; other mods\' recipes left out)."""',
             "", "FAN_RECIPES = {"]
    for key, recipe in table.items():
        lines.append(f"    {key!r}: {json.dumps(recipe, sort_keys=True)},")
    lines.append("}")
    (HERE / "fan_recipes.py").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(table), "recipes")


if __name__ == "__main__":
    main()
