"""One-off generator for the milling and crushing recipe tables (not a plugin: the leading
underscore keeps tools/gen_content.py from loading it). Reads Create's datagen output and
writes _millstone_recipes.py and _crushing_wheel_recipes.py beside it; the plugins import those,
so the build never needs the Create checkout.

    python tools/content/_millstone_gen.py C:/Users/latif/Claude/Projects/create-java-src

Recipes behind `neoforge:conditions` are left out, except the ones whose only condition is
`not mod_loaded` (Create's own recipes that another mod replaces when it is loaded: none is
loaded here, so they apply).
"""

import json
import pprint
import sys
from pathlib import Path


def keep(recipe):
    conditions = recipe.get("neoforge:conditions")
    if not conditions:
        return True
    return all(c.get("type") == "neoforge:not" and c["value"].get("type") == "neoforge:mod_loaded"
               for c in conditions)


def table(folder):
    out = {}
    for path in sorted(folder.glob("*.json")):  # top level only: compat/ is other mods'
        recipe = json.loads(path.read_text(encoding="utf-8"))
        if not keep(recipe):
            continue
        recipe.pop("neoforge:conditions", None)
        out[f"{folder.name}/{path.stem}"] = recipe
    return out


def main():
    create = Path(sys.argv[1])
    recipes = create / "src" / "generated" / "resources" / "data" / "create" / "recipe"
    here = Path(__file__).resolve().parent
    for kind, name, const in (("milling", "_millstone_recipes.py", "MILLING"),
                              ("crushing", "_crushing_wheel_recipes.py", "CRUSHING")):
        found = table(recipes / kind)
        text = (f'"""Create\'s `create:{kind}` recipes as its datagen writes them '
                f'(generated by _millstone_gen.py)."""\n\n{const} = '
                f'{pprint.pformat(found, width=100, sort_dicts=True)}\n')
        (here / name).write_text(text, encoding="utf-8", newline="\n")
        print(name, len(found))


if __name__ == "__main__":
    main()
