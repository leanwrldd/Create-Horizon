"""Writes `native/kinetics/src/rules/filter_items.rs`: the vanilla facts the Attribute Filter asks
about an item that Horizon can't be asked at run time, read from Horizon's prepared data
(`%APPDATA%/horizon/.horizon-cache/mod-content/<hash>/items.json`, `data/minecraft/enchantment`,
`data/minecraft/tags/item`) and from the item tags this project's plugins declare.

    python tools/content/_filter_items_gen.py

The plugin loader skips files that start with `_`.
"""
import glob
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "native" / "kinetics" / "src" / "rules" / "filter_items.rs"

# `FluidBucketWrapper` (NeoForge): vanilla's buckets and what they hold (`Capabilities.FluidHandler.ITEM`).
BUCKETS = [
    ("minecraft:bucket", ""),
    ("minecraft:water_bucket", "minecraft:water"),
    ("minecraft:lava_bucket", "minecraft:lava"),
    ("minecraft:milk_bucket", "minecraft:milk"),
    ("minecraft:cod_bucket", "minecraft:water"),
    ("minecraft:salmon_bucket", "minecraft:water"),
    ("minecraft:tropical_fish_bucket", "minecraft:water"),
    ("minecraft:pufferfish_bucket", "minecraft:water"),
    ("minecraft:axolotl_bucket", "minecraft:water"),
    ("minecraft:tadpole_bucket", "minecraft:water"),
]


def prepared():
    base = Path(os.path.expandvars("%APPDATA%/horizon/.horizon-cache/mod-content"))
    return next(p for p in sorted(base.iterdir()) if (p / "items.json").exists())


def strings(name, values):
    body = "".join(f'    "{value}",\n' for value in values)
    return f"pub const {name}: &[&str] = &[\n{body}];\n\n"


def main():
    data = prepared()
    items = json.loads((data / "items.json").read_text(encoding="utf8"))
    food = sorted(k for k, v in items.items() if "minecraft:food" in v)
    fuel = sorted(k for k, v in items.items() if "minecraft:cooking_fuel" in v)
    equipable = sorted(k for k, v in items.items()
                       if v.get("minecraft:equippable", {}).get("slot") not in (None, "mainhand", "offhand"))
    damage = sorted((k, v["minecraft:max_damage"]) for k, v in items.items() if "minecraft:max_damage" in v)
    enchant = []
    for path in sorted(glob.glob(str(data / "data/minecraft/enchantment/*.json"))):
        enchant.append((f"minecraft:{Path(path).stem}", json.load(open(path, encoding="utf8"))["max_level"]))
    tags = set()
    root = data / "data/minecraft/tags/item"
    for path in root.rglob("*.json"):
        tags.add("minecraft:" + path.relative_to(root).with_suffix("").as_posix())
    for plugin in (ROOT / "tools").glob("**/*.py"):
        for namespace, name in re.findall(r'"(c|create):item/([a-z0-9_/]+)"', plugin.read_text(encoding="utf8")):
            tags.add(f"{namespace}:{name}")

    out = ["//! Generated by tools/content/_filter_items_gen.py from Horizon's prepared data: do not edit.\n",
           "//!\n",
           "//! Vanilla facts the Attribute Filter asks of an item (`rules::filter`): the items with a food\n",
           "//! component, a fuel burn time or an equippable slot other than a hand, durabilities, enchantment\n",
           "//! maximum levels and the item tags a filter can offer, which Horizon can't be asked to list.\n\n"]
    out.append(strings("FOOD", food))
    out.append(strings("FUEL", fuel))
    out.append(strings("EQUIPABLE", equipable))
    out.append("pub const MAX_DAMAGE: &[(&str, u32)] = &[\n")
    out += [f'    ("{k}", {v}),\n' for k, v in damage]
    out.append("];\n\npub const ENCHANT_MAX: &[(&str, u32)] = &[\n")
    out += [f'    ("{k}", {v}),\n' for k, v in enchant]
    out.append("];\n\n")
    out.append("/// `FluidBucketWrapper`: a bucket and the fluid in it (empty for none).\n")
    out.append("pub const BUCKETS: &[(&str, &str)] = &[\n")
    out += [f'    ("{k}", "{v}"),\n' for k, v in BUCKETS]
    out.append("];\n\n")
    out.append(strings("ITEM_TAGS", sorted(tags)))
    out.append(
        "pub fn is_food(item: &str) -> bool {\n    FOOD.contains(&item)\n}\n\n"
        "pub fn is_fuel(item: &str) -> bool {\n    FUEL.contains(&item)\n}\n\n"
        "pub fn is_equipable(item: &str) -> bool {\n    EQUIPABLE.contains(&item)\n}\n\n"
        "pub fn max_damage(item: &str) -> Option<u32> {\n"
        "    MAX_DAMAGE.iter().find(|(id, _)| *id == item).map(|(_, damage)| *damage)\n}\n\n"
        "pub fn enchant_max(id: &str) -> Option<u32> {\n"
        "    ENCHANT_MAX.iter().find(|(name, _)| *name == id).map(|(_, level)| *level)\n}\n\n"
        "/// The fluid a bucket holds: `Some(\"\")` for an empty bucket, none for another item.\n"
        "pub fn bucket_fluid(item: &str) -> Option<&'static str> {\n"
        "    BUCKETS.iter().find(|(id, _)| *id == item).map(|(_, fluid)| *fluid)\n}\n\n"
        "#[cfg(test)]\nmod tests {\n    use super::*;\n\n"
        "    #[test]\n    fn the_tables_know_vanilla() {\n"
        "        assert!(is_food(\"minecraft:apple\"));\n"
        "        assert!(!is_food(\"minecraft:stone\"));\n"
        "        assert!(is_fuel(\"minecraft:coal\"));\n"
        "        assert!(is_equipable(\"minecraft:iron_helmet\"));\n"
        "        assert!(!is_equipable(\"minecraft:shield\"));\n"
        "        assert_eq!(max_damage(\"minecraft:diamond_sword\"), Some(1561));\n"
        "        assert_eq!(enchant_max(\"minecraft:sharpness\"), Some(5));\n"
        "        assert_eq!(bucket_fluid(\"minecraft:water_bucket\"), Some(\"minecraft:water\"));\n"
        "        assert!(ITEM_TAGS.contains(&\"minecraft:logs\"));\n"
        "    }\n}\n")
    OUT.write_text("".join(out), encoding="utf8", newline="\n")
    print(f"{OUT}: {len(food)} food, {len(fuel)} fuel, {len(equipable)} equipable, {len(damage)} damage, "
          f"{len(enchant)} enchantments, {len(tags)} tags")


if __name__ == "__main__":
    main()
