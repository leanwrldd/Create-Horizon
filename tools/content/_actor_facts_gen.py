"""One-off generator for the block facts the actor rules read (not a plugin: the leading underscore
keeps tools/gen_content.py from loading it). Writes native/kinetics/src/rules/actor_facts.rs.

    python tools/content/_actor_facts_gen.py [prepared game data dir]

The Harvester, Plough and Roller ask a block state which class it is (`instanceof CropBlock`,
`BushBlock`, `GrowingPlantBlock`, `FallingBlock`, `FarmBlock`...) and how many ages its `age`
property has (`IntegerProperty.getPossibleValues().size()`). Horizon's `Host` can answer neither, so
vanilla's are baked in from the prepared game data (`block-behaviours.json` lists each block's class
chain and interfaces, `model-states.json` its property schema). Rerun it when the game version
changes. Mojang's `BushBlock` is `VegetationBlock` in this version.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"
OUT = ROOT / "native/kinetics/src/rules/actor_facts.rs"


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    blocks = json.loads((data / "block-behaviours.json").read_text(encoding="utf-8"))["blocks"]
    schemas = json.loads((data / "model-states.json").read_text(encoding="utf-8"))

    def with_class(*names):
        return sorted(b["name"] for b in blocks
                      if b["name"].startswith("minecraft:") and any(c in names for c in b["class"]))

    groups = {
        "CROP": with_class("CropBlock"),
        "VEGETATION": with_class("VegetationBlock"),
        "GROWING_PLANT": with_class("GrowingPlantBlock"),
        "SUGAR_CANE": with_class("SugarCaneBlock"),
        "MUSHROOM": with_class("MushroomBlock"),
        "COCOA": with_class("CocoaBlock"),
        "SWEET_BERRY": with_class("SweetBerryBushBlock"),
        "FALLING": with_class("FallingBlock"),
        "FARMLAND": with_class("FarmlandBlock"),
        "LEAVES": with_class("LeavesBlock"),
    }
    # `ItemStack(state.getBlock())`: the item a block stands for, where it isn't the block's own name
    # (wheat's is wheat_seeds). `facts.json` names each state's block, `gameplay-facts.json` its item.
    facts = json.loads((data / "facts.json").read_text(encoding="utf-8"))["states"]
    gameplay = json.loads((data / "gameplay-facts.json").read_text(encoding="utf-8"))["states"]
    planted = set(groups["CROP"]) | set(groups["VEGETATION"]) | set(groups["SWEET_BERRY"]) | set(groups["COCOA"])
    items = {}
    for state, extra in zip(facts, gameplay):
        name = state[0]
        if name in planted and extra["item"] not in ("minecraft:air", name):
            items[name] = extra["item"]
    special = sorted(b["name"] for b in blocks
                     if b["name"].startswith("minecraft:") and "SpecialPlantable" in b.get("interfaces", []))
    ages = []
    for name, entry in sorted(schemas.items()):
        if not name.startswith("minecraft:"):
            continue
        age = entry.get("schema", {}).get("age")
        if age and "integer" in age:
            low, high = age["integer"]
            ages.append((name, high - low + 1))

    docs = {
        "CROP": "`instanceof CropBlock`.",
        "VEGETATION": "`instanceof BushBlock` (`VegetationBlock` in this version).",
        "GROWING_PLANT": "`instanceof GrowingPlantBlock`.",
        "SUGAR_CANE": "`instanceof SugarCaneBlock`.",
        "MUSHROOM": "`instanceof MushroomBlock`.",
        "COCOA": "`instanceof CocoaBlock`.",
        "SWEET_BERRY": "`instanceof SweetBerryBushBlock`.",
        "FALLING": "`instanceof FallingBlock`.",
        "FARMLAND": "`instanceof FarmBlock`.",
        "LEAVES": "`BlockTags.LEAVES` as a class: `LeavesBlock`.",
    }
    text = ['//! Generated by tools/content/_actor_facts_gen.py: do not edit by hand.\n//!\n'
            '//! What the Harvester, Plough and Roller ask a vanilla block that Horizon\'s `Host` cannot\n'
            '//! answer: its class and the number of values of its `age` property, from the prepared game data.\n']
    for key, names in groups.items():
        text.append(f"\n/// {docs[key]}\npub const {key}: &[&str] = &[\n")
        text.extend(f'    "{n}",\n' for n in names)
        text.append("];\n")
    text.append("\n/// `instanceof SpecialPlantable`.\npub const SPECIAL_PLANTABLE: &[&str] = &[\n")
    text.extend(f'    "{n}",\n' for n in special)
    text.append("];\n")
    text.append("\n/// `IntegerProperty.getPossibleValues().size()` of a block's `age` property.\n"
                "pub const AGE_VALUES: &[(&str, i32)] = &[\n")
    text.extend(f'    ("{n}", {v}),\n' for n, v in ages)
    text.append("];\n")
    text.append("\n/// `Block.asItem()` where it isn't the block's own id.\npub const BLOCK_ITEM: &[(&str, &str)] = &[\n")
    text.extend(f'    ("{n}", "{i}"),\n' for n, i in sorted(items.items()))
    text.append("];\n")
    OUT.write_text("".join(text), encoding="utf-8", newline="\n")
    print({k: len(v) for k, v in groups.items()}, len(special), len(ages))


main()
