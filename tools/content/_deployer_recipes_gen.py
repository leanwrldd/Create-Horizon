"""One-off generator for the Deployer's recipe table (not a plugin: the leading underscore keeps
tools/gen_content.py from loading it). Reads Create's datagen output and writes
_deployer_recipes.py beside it; deployer.py imports that, so the build never needs the Create
checkout. It also writes the two other recipe types a Deployer's held item selects: the sandpaper
polishing recipes and the sequenced assembly recipes (`machines/sand_paper.rs` and
`machines/sequenced.rs`).

    python tools/content/_deployer_recipes_gen.py C:/Users/latif/Claude/Projects/create-java-src

DEPLOYING: every `create:deploying` recipe of Create's datagen (`recipe/deploying/*.json`), as it
writes them. ITEM_APPLICATION: every `create:item_application` recipe (`recipe/item_application/*.json`).
SANDPAPER_POLISHING: every `create:sandpaper_polishing` recipe (`recipe/sandpaper_polishing/*.json`).
SEQUENCED_ASSEMBLY: every `create:sequenced_assembly` recipe (`recipe/sequenced_assembly/*.json`).

Left out, and printed: a recipe that names an item or block of Create this mod doesn't declare
yet (a sequenced assembly is checked through its steps, its transitional item and its results:
the Track's needs the Track), and one behind `neoforge:conditions`.
"""

import json
import pprint
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))


def declared():
    """Every `create:` id the mod declares as a block or an item."""
    import gen_content
    collected = gen_content.collect()
    return {f"create:{name}" for name in (*collected.blocks, *collected.items)}


def needs(recipe):
    """The `create:` ids a recipe names as an `item` or an `id`, at any depth (a sequenced
    assembly has its steps and its transitional item inside)."""
    ids = set()

    def walk(value):
        if isinstance(value, dict):
            for key, inner in value.items():
                if key in ("item", "id") and isinstance(inner, str) and inner.startswith("create:"):
                    ids.add(inner)
                else:
                    walk(inner)
        elif isinstance(value, list):
            for inner in value:
                walk(inner)

    walk(recipe)
    return ids


def table(folder, kind, have, left_out):
    out = {}
    for path in sorted(folder.glob("*.json")):
        recipe = json.loads(path.read_text(encoding="utf-8"))
        name = f"{folder.name}/{path.stem}"
        if recipe.get("neoforge:conditions"):
            left_out.append((name, "neoforge:conditions"))
            continue
        assert recipe["type"] == kind, (name, recipe["type"])
        missing = sorted(needs(recipe) - have)
        if missing:
            left_out.append((name, ", ".join(missing)))
            continue
        out[name] = recipe
    return out


def main():
    create = Path(sys.argv[1])
    data = create / "src" / "generated" / "resources" / "data" / "create" / "recipe"
    have = declared()
    left_out = []
    deploying = table(data / "deploying", "create:deploying", have, left_out)
    application = table(data / "item_application", "create:item_application", have, left_out)
    polishing = table(data / "sandpaper_polishing", "create:sandpaper_polishing", have, left_out)
    assembly = table(data / "sequenced_assembly", "create:sequenced_assembly", have, left_out)
    (HERE / "_deployer_recipes.py").write_text(
        '"""Create\'s `create:deploying`, `create:item_application`, `create:sandpaper_polishing` and '
        "`create:sequenced_assembly` recipes as its datagen writes them (generated by "
        '_deployer_recipes_gen.py)."""\n\n'
        f"DEPLOYING = {pprint.pformat(deploying, width=100, sort_dicts=True)}\n\n"
        f"ITEM_APPLICATION = {pprint.pformat(application, width=100, sort_dicts=True)}\n\n"
        f"SANDPAPER_POLISHING = {pprint.pformat(polishing, width=100, sort_dicts=True)}\n\n"
        f"SEQUENCED_ASSEMBLY = {pprint.pformat(assembly, width=100, sort_dicts=True)}\n",
        encoding="utf-8", newline="\n")
    print(f"{len(deploying)} deploying, {len(application)} item application, "
          f"{len(polishing)} sandpaper polishing, {len(assembly)} sequenced assembly")
    for name, why in left_out:
        print(f"left out {name}: {why}")


if __name__ == "__main__":
    main()
