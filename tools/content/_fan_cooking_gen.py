"""One-off generator for the Encased Fan's smoking and blasting tables (not a plugin: the leading
underscore keeps tools/gen_content.py from loading it). Writes _fan_cooking.py beside it; fan.py
imports that, so the build never needs the game data.

    python tools/content/_fan_cooking_gen.py [prepared game data dir]

Horizon's `Host::recipes_of_type` answers only types outside `minecraft`, so a mod cannot read
vanilla's smelting, smoking and blasting recipes (`RecipeManager.getRecipeFor(RecipeType.SMELTING,
..)`, which `AllFanProcessingTypes.SmokingType` and `BlastingType` ask). This copies them from the
prepared game data (`data/minecraft/recipe`, the way `_crafter_recipes_gen.py` copies crafting and
`_saw_recipes_gen.py` stonecutting) into recipes of three types of this mod, in Create's own shape
(`ingredients`, `results`, `processing_time` = the recipe's cooking time):

    minecraft:smelting -> create:baked_smelting
    minecraft:smoking  -> create:baked_smoking
    minecraft:blasting -> create:baked_blasting

and the items that carry `minecraft:damage_resistant` against fire (`#minecraft:is_fire`), which is
what Create 1.21.1's `DataComponents.FIRE_RESISTANT` became (`BlastingType.canProcess` burns every
item that has none), as the item tag `create:fan_fire_resistant`.

DROP THESE when the project moves to the new mod API's `recipe_for`, which reads vanilla's
recipes: the three baked types, this file, `_fan_cooking.py`, and the tag. A data pack's changes to
vanilla's cooking recipes are not seen until then.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_DATA = Path.home() / "AppData/Roaming/horizon/.horizon-cache/mod-content/5cce03fe38433e65"

TYPES = {
    "minecraft:smelting": "create:baked_smelting",
    "minecraft:smoking": "create:baked_smoking",
    "minecraft:blasting": "create:baked_blasting",
}


def cooking(data):
    """The three kinds of cooking recipe, keyed `<kind>/<vanilla file name>`."""
    out = {}
    for path in sorted((data / "data" / "minecraft" / "recipe").glob("*.json")):
        recipe = json.loads(path.read_text(encoding="utf-8"))
        kind = TYPES.get(recipe["type"])
        if kind is None:
            continue
        result = recipe["result"]
        out[f"{kind.split(':')[1]}/{path.stem}"] = {
            "type": kind,
            "ingredients": [recipe["ingredient"]],
            "processing_time": recipe.get("cookingtime", 200),
            "results": [{k: v for k, v in result.items() if k in ("id", "count", "components")}],
        }
    return out


def fire_resistant(data):
    """Items whose default components make them immune to fire."""
    items = json.loads((data / "items.json").read_text(encoding="utf-8"))
    return sorted(name for name, comps in items.items()
                  if comps.get("minecraft:damage_resistant", {}).get("types") == "#minecraft:is_fire")


def main():
    data = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    recipes = cooking(data)
    resistant = fire_resistant(data)
    lines = ['"""Vanilla\'s smelting, smoking and blasting recipes copied as `create:baked_*` recipes, and the',
             "items immune to fire (generated by _fan_cooking_gen.py from the prepared game data; the",
             'Encased Fan\'s smoking and blasting read them; drop when the mod API gives `recipe_for`)."""',
             "", "COOKING = {"]
    for key, recipe in recipes.items():
        lines.append(f"    {key!r}: {json.dumps(recipe, sort_keys=True)},")
    lines += ["}", "", "FIRE_RESISTANT = ["]
    lines += [f"    {name!r}," for name in resistant]
    lines.append("]")
    (HERE / "_fan_cooking.py").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    counts = {kind: sum(1 for r in recipes.values() if r["type"] == kind) for kind in TYPES.values()}
    print(counts, len(resistant), "fire resistant items")


if __name__ == "__main__":
    main()
