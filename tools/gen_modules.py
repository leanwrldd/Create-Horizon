"""Write the two module lists the machine modules hang from, from the files that exist:

    mod/src/machines/mod.rs              every machines/<name>.rs, and `all()` calling each `hooks()`
    mod/src/kinetics/src/rules/mod.rs    every rules/<name>.rs

    python tools/gen_modules.py [package dir, default mod/]

Run it after adding or removing a module file. `tools/check_module.sh` runs it on its own copy.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
native = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "mod"


def names(folder: Path):
    folder.mkdir(parents=True, exist_ok=True)
    files = [p.stem for p in folder.glob("*.rs") if p.stem != "mod"]
    # a module that grew into a folder: <name>/mod.rs
    folders = [p.parent.name for p in folder.glob("*/mod.rs")]
    return sorted(set(files + folders))


def write(path: Path, lines):
    text = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


machines = native / "src" / "machines"
found = names(machines)
write(machines / "mod.rs", [
    "//! Generated by tools/gen_modules.py from the files in this folder: do not edit by hand.",
    "//!",
    "//! One module per machine (or family of blocks). Each is a `Hooks` of its own, answering",
    "//! only for its own blocks, and exports `pub fn hooks() -> Box<dyn Hooks>`.",
    "",
    "use crate::compat::Hooks;",
    "",
    *(f"pub mod {name};" for name in found),
    "",
    "pub fn all() -> Vec<Box<dyn Hooks>> {",
    "    vec![" + ", ".join(f"{name}::hooks()" for name in found) + "]",
    "}",
])
rules = native / "src" / "kinetics" / "src" / "rules"
found_rules = names(rules)
write(rules / "mod.rs", [
    "//! Generated by tools/gen_modules.py from the files in this folder: do not edit by hand.",
    "//!",
    "//! The rules of one machine per module: numbers and state machines ported from Create, with",
    "//! no game types, so `cargo test` covers them.",
    "",
    *(f"pub mod {name};" for name in found_rules),
])
print(f"machines: {', '.join(found) or 'none'}; rules: {', '.join(found_rules) or 'none'}")
