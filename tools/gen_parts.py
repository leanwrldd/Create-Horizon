"""Write mod/src/parts_gen.rs: the lists `Hooks::register` attaches a Part to.

    python tools/gen_parts.py

* BLOCKS         every block the content declares (content/data/create/horizon/block/*.json): each gets one
                 `CreateBlock` Part (mod/src/parts.rs), which forwards its methods into the old modules.
* BLOCK_ENTITIES the blocks that have a block entity: each also gets a block entity type of the same name and one
                 `CreateEntity` Part. The old API let a module answer `block_entity` for a block name, so the list
                 comes from asking the modules: `tools/dump_block_entities.sh` runs the ignored test
                 `dump_block_entities` over BLOCKS and writes tools/block_entities.txt, which this script reads.

The Parts hold the block's full id; one Part per block is registered, so a new block in the content shows up here
after `python tools/gen_content.py` and a rerun of this script.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
blocks = sorted(p.stem for p in (ROOT / "content" / "data" / "create" / "horizon" / "block").glob("*.json"))
listing = ROOT / "tools" / "block_entities.txt"
entities = []
if listing.exists():
    entities = sorted(line.strip() for line in listing.read_text(encoding="utf-8").splitlines()
                      if line.strip() and not line.startswith("#"))
unknown = [name for name in entities if name not in blocks]
if unknown:
    raise SystemExit(f"tools/block_entities.txt names blocks the content doesn't declare: {unknown}")


def rust_list(name, items):
    out = [f"pub(crate) const {name}: &[&str] = &["]
    out += [f'    "{item}",' for item in items]
    out.append("];")
    return out


text = ["// Generated by tools/gen_parts.py: do not edit by hand.", ""]
text += rust_list("BLOCKS", blocks) + [""] + rust_list("BLOCK_ENTITIES", entities)
(ROOT / "mod" / "src" / "parts_gen.rs").write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")
print(f"{len(blocks)} blocks, {len(entities)} with a block entity")
